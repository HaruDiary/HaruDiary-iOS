import Foundation

/// Questions to start writing from. The same day gives the same question; `skip` moves on to the next ones.
enum DiaryPrompts {
    static let all = [
        "오늘 가장 기억에 남는 순간은 언제였나요?",
        "오늘 고마웠던 일을 하나 적어볼까요?",
        "오늘 나를 웃게 한 것은 무엇이었나요?",
        "오늘 가장 오래 생각한 것은 무엇인가요?",
        "오늘 먹은 것 중 가장 맛있었던 것은 무엇인가요?",
        "오늘 누구와 어떤 이야기를 나눴나요?",
        "오늘 새로 알게 된 것이 있나요?",
        "오늘 하루를 한 단어로 표현한다면 무엇인가요?",
        "오늘 가장 힘들었던 일은 무엇이었나요?",
        "오늘 스스로를 칭찬하고 싶은 일은 무엇인가요?",
        "오늘 본 풍경 중 마음에 남은 장면이 있나요?",
        "지금 가장 기대하고 있는 일은 무엇인가요?",
        "오늘 아쉬웠던 일은 무엇이고, 다시 한다면 어떻게 할까요?",
        "요즘 자주 듣는 노래나 자주 보는 것은 무엇인가요?",
        "오늘 몸과 마음의 상태는 어땠나요?",
        "오늘 나에게 가장 큰 영향을 준 사람은 누구인가요?",
        "내일의 나에게 한마디를 남긴다면 무엇인가요?",
        "오늘 미뤄둔 일이 있다면 무엇인가요?",
        "최근에 받은 작은 친절이 있었나요?",
        "오늘 가장 편안했던 시간은 언제였나요?",
        "요즘 걱정하고 있는 일은 무엇인가요?",
        "오늘 한 일 중 가장 잘한 선택은 무엇인가요?",
        "지금 창밖은 어떤 모습인가요?",
        "오늘 하루 중 다시 돌아가고 싶은 순간이 있나요?",
        "요즘 새로 시작해 보고 싶은 것은 무엇인가요?",
        "오늘 나를 지치게 한 것과 쉬게 한 것은 무엇인가요?",
        "오늘 누군가에게 해주고 싶었던 말이 있나요?",
        "일주일 전의 나와 달라진 점이 있나요?",
        "오늘 가장 오래 머문 곳은 어디였나요?",
        "오늘을 사진 한 장으로 남긴다면 어떤 장면인가요?",
    ]

    static func prompt(on date: Date, calendar: Calendar, skip: Int = 0) -> String {
        let day = calendar.ordinality(of: .day, in: .era, for: date) ?? 0
        let index = ((day + skip) % all.count + all.count) % all.count
        return all[index]
    }
}
